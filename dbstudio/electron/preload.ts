import { contextBridge, ipcRenderer } from 'electron'
import type { DbApi } from '../shared/types'

const api: DbApi = {
  connect: (config) => ipcRenderer.invoke('db:connect', config),
  test: (config) => ipcRenderer.invoke('db:test', config),
  disconnect: (id) => ipcRenderer.invoke('db:disconnect', id),
  listDatabases: (id) => ipcRenderer.invoke('db:listDatabases', id),
  switchDatabase: (id, database) => ipcRenderer.invoke('db:switchDatabase', id, database),
  listTables: (id) => ipcRenderer.invoke('db:listTables', id),
  listColumns: (id, table) => ipcRenderer.invoke('db:listColumns', id, table),
  query: (id, sql) => ipcRenderer.invoke('db:query', id, sql),
  queryMulti: (id, sql, maxRows) => ipcRenderer.invoke('db:queryMulti', id, sql, maxRows),
  cancel: (id) => ipcRenderer.invoke('db:cancel', id),
  listObjects: (id) => ipcRenderer.invoke('db:listObjects', id),
  getDefinition: (id, target) => ipcRenderer.invoke('db:getDefinition', id, target),
  getStructure: (id, table) => ipcRenderer.invoke('db:getStructure', id, table),
  applyChanges: (id, changes) => ipcRenderer.invoke('db:applyChanges', id, changes),
  openSession: (parentId) => ipcRenderer.invoke('db:openSession', parentId),
  closeSession: (parentId, id) => ipcRenderer.invoke('db:closeSession', parentId, id),
  exportData: (data, format, name, table, engine) => ipcRenderer.invoke('export:save', data, format, name, table, engine),
  selectPage: (id, table, options) => ipcRenderer.invoke('db:selectPage', id, table, options),
  explain: (id, sql) => ipcRenderer.invoke('db:explain', id, sql),
  transaction: (id, action) => ipcRenderer.invoke('db:transaction', id, action),
  readImportFile: (file) => ipcRenderer.invoke('import:read', file),
  aiAsk: (req) => ipcRenderer.invoke('ai:ask', req),
  aiHasKey: () => ipcRenderer.invoke('ai:hasKey'),
  aiSetKey: (key, model) => ipcRenderer.invoke('ai:setKey', key, model),
  logError: (text) => ipcRenderer.invoke('log:error', text),
  openLogFolder: () => ipcRenderer.invoke('log:open'),
  selectTop: (id, table, limit) => ipcRenderer.invoke('db:selectTop', id, table, limit),
  applyUpdates: (id, updates) => ipcRenderer.invoke('db:applyUpdates', id, updates),
  listSaved: () => ipcRenderer.invoke('store:list'),
  saveConnection: (c) => ipcRenderer.invoke('store:save', c),
  deleteSaved: (id) => ipcRenderer.invoke('store:delete', id),
  pickFile: (kind) => ipcRenderer.invoke('dialog:pickFile', kind),
  saveTextFile: (content, opts) => ipcRenderer.invoke('file:saveText', content, opts),
  openTextFile: (opts) => ipcRenderer.invoke('file:openText', opts),
  listSchedules: () => ipcRenderer.invoke('schedules:list'),
  saveSchedule: (s) => ipcRenderer.invoke('schedules:save', s),
  deleteSchedule: (id) => ipcRenderer.invoke('schedules:delete', id),
  runSchedule: (id) => ipcRenderer.invoke('schedules:run', id),
  revealScheduleFile: (id) => ipcRenderer.invoke('schedules:reveal', id),
  onSchedulesChanged: (fn) => { const f = () => fn(); ipcRenderer.on('schedules:changed', f); return () => { ipcRenderer.removeListener('schedules:changed', f) } },
  pickFolder: () => ipcRenderer.invoke('dialog:pickFolder'),
  appVersion: () => ipcRenderer.invoke('app:version'),
  checkForUpdate: (url) => ipcRenderer.invoke('app:checkUpdate', url),
  getLicence: () => ipcRenderer.invoke('licence:get'),
  setLicence: (key) => ipcRenderer.invoke('licence:set', key),
  clearLicence: () => ipcRenderer.invoke('licence:clear'),
  readTeam: (folder) => ipcRenderer.invoke('team:read', folder),
  shareToTeam: (folder, data) => ipcRenderer.invoke('team:share', folder, data)
}

contextBridge.exposeInMainWorld('db', api)
