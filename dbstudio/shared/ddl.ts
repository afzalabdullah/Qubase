// SQL generation for the table designer, scripts and sidebar actions.
// Kept in one place so the UI can preview exactly what will run.
import type { ColumnInfo, ForeignKeyInfo, IndexInfo, TableInfo } from './types'

/** Engine names as in shared/drivers.ts (postgres, mysql, mssql, sqlite, oracle, duckdb, clickhouse, libsql…) */
export type Engine = string

export function quote(engine: Engine, name: string) {
  if (engine === 'mssql') return `[${name.replace(/]/g, ']]')}]`
  if (engine === 'mysql' || engine === 'clickhouse' || engine === 'bigquery') return `\`${name.replace(/`/g, '``')}\``
  return `"${name.replace(/"/g, '""')}"`
}

export function tableRef(engine: Engine, t: { schema?: string; name: string }) {
  // SQLite/LibSQL have no schemas worth writing; MySQL's "schema" is the current database.
  if (!t.schema || engine === 'sqlite' || engine === 'libsql' || engine === 'mysql') return quote(engine, t.name)
  return `${quote(engine, t.schema)}.${quote(engine, t.name)}`
}

/** A value written as an SQL literal (for generated INSERT / UPDATE scripts) */
export function sqlLiteral(v: unknown): string {
  if (v === null || v === undefined) return 'NULL'
  if (typeof v === 'number' || typeof v === 'bigint') return String(v)
  if (typeof v === 'boolean') return v ? '1' : '0'
  const s = v instanceof Date ? v.toISOString() : typeof v === 'object' ? JSON.stringify(v) : String(v)
  return `'${s.replace(/'/g, "''")}'`
}

