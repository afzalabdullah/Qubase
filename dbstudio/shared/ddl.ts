/** A column in the designer. `original` is its name when loaded (undefined = new column). */
export interface DesignColumn extends ColumnInfo {
  original?: string
  dropped?: boolean
}

function columnDef(engine: Engine, c: ColumnInfo, inlinePk = false) {
  let type = c.dataType.trim() || 'varchar(255)'
  if (engine === 'clickhouse' && c.nullable && !/^Nullable\(/i.test(type)) type = `Nullable(${type})`
  const parts = [quote(engine, c.name), type]
  if (c.autoIncrement) {
    if (engine === 'mssql') parts.push('IDENTITY(1,1)')
    else if (engine === 'postgres' || engine === 'oracle') parts.push('GENERATED BY DEFAULT AS IDENTITY')
  }
  // DEFAULT before NULL / NOT NULL: Oracle requires this order and the others accept it
  if (c.defaultValue !== undefined && c.defaultValue !== null && c.defaultValue !== '' && !c.autoIncrement) parts.push(`DEFAULT ${c.defaultValue}`)
  if (engine !== 'clickhouse') parts.push(c.nullable && !c.primaryKey ? 'NULL' : 'NOT NULL')
  if (inlinePk) parts.push('PRIMARY KEY' + (c.autoIncrement ? ' AUTOINCREMENT' : ''))
  if (c.autoIncrement && engine === 'mysql') parts.push('AUTO_INCREMENT')
  return parts.join(' ')
}

export function createTableSql(
  engine: Engine,
  t: TableInfo,
  s: { columns: ColumnInfo[]; indexes?: IndexInfo[]; foreignKeys?: ForeignKeyInfo[] }
) {
  const pk = s.columns.filter((c) => c.primaryKey).map((c) => c.name)
  // SQLite needs "INTEGER PRIMARY KEY AUTOINCREMENT" inline for auto-numbering
  const sqliteInline = (engine === 'sqlite' || engine === 'libsql') && pk.length === 1 && s.columns.find((c) => c.name === pk[0])?.autoIncrement
  const lines = s.columns.map((c) => '  ' + columnDef(engine, c, !!sqliteInline && c.name === pk[0]))
  if (pk.length && !sqliteInline && engine !== 'clickhouse') lines.push(`  PRIMARY KEY (${pk.map((c) => quote(engine, c)).join(', ')})`)
  for (const fk of s.foreignKeys ?? []) {
    lines.push(`  CONSTRAINT ${quote(engine, fk.name)} FOREIGN KEY (${fk.columns.map((c) => quote(engine, c)).join(', ')}) REFERENCES ${tableRef(engine, { schema: fk.refSchema, name: fk.refTable })} (${fk.refColumns.map((c) => quote(engine, c)).join(', ')})`)
  }
  let out = `CREATE TABLE ${tableRef(engine, t)} (\n${lines.join(',\n')}\n)`
  if (engine === 'clickhouse') out += `\nENGINE = MergeTree\nORDER BY ${pk.length ? `(${pk.map((c) => quote(engine, c)).join(', ')})` : 'tuple()'}`
  out += ';'
  for (const ix of s.indexes ?? []) if (!ix.primary) out += '\n' + createIndexSql(engine, t, ix.name, ix.columns, ix.unique)
  return out
}

/**
 * ALTER statements turning `before` into `after`. Some changes can't be made in
 * place on some engines; those come back as warnings instead of SQL.
 */
export function alterTableSql(engine: Engine, t: TableInfo, before: ColumnInfo[], after: DesignColumn[]) {
  const ref = tableRef(engine, t)
  const q = (n: string) => quote(engine, n)
  const sql: string[] = []
  const warnings: string[] = []
  const byName = new Map(before.map((c) => [c.name, c]))
  const sqlite = engine === 'sqlite' || engine === 'libsql'

  for (const c of after) {
    if (c.original === undefined) {
      if (c.dropped || !c.name.trim()) continue
      const def = columnDef(engine, { ...c, primaryKey: false })
      sql.push(engine === 'mssql' ? `ALTER TABLE ${ref} ADD ${def};`
        : engine === 'oracle' ? `ALTER TABLE ${ref} ADD (${def});`
        : `ALTER TABLE ${ref} ADD COLUMN ${def};`)
      if (c.primaryKey) warnings.push(`New column "${c.name}" was added without primary key; change the primary key manually.`)
      continue
    }
    const old = byName.get(c.original)
    if (!old) continue
    if (c.dropped) { sql.push(`ALTER TABLE ${ref} DROP COLUMN ${q(old.name)};`); continue }

    const renamed = c.name !== old.name
    const typeChanged = c.dataType.trim() !== old.dataType.trim()
    const nullChanged = c.nullable !== old.nullable
    const defChanged = (c.defaultValue ?? '') !== (old.defaultValue ?? '')
    if (c.primaryKey !== old.primaryKey) warnings.push(`Primary key change on "${c.name}" is not generated; change the primary key manually.`)

    if (engine === 'mysql') {
      if (renamed || typeChanged || nullChanged || defChanged) sql.push(`ALTER TABLE ${ref} CHANGE COLUMN ${q(old.name)} ${columnDef(engine, { ...c, primaryKey: false })};`)
      continue
    }
    if (renamed) {
      sql.push(engine === 'mssql'
        ? `EXEC sp_rename '${(t.schema ? t.schema + '.' : '') + t.name}.${old.name}', '${c.name}', 'COLUMN';`
        : `ALTER TABLE ${ref} RENAME COLUMN ${q(old.name)} TO ${q(c.name)};`)
    }
    const col = q(c.name)
    if (sqlite) {
      if (typeChanged || nullChanged || defChanged) warnings.push(`SQLite can't change the type, NULL or default of "${c.name}" in place. Create a new table and copy the data.`)
      continue
    }
    if (engine === 'mssql') {
      if (typeChanged || nullChanged) sql.push(`ALTER TABLE ${ref} ALTER COLUMN ${col} ${c.dataType} ${c.nullable ? 'NULL' : 'NOT NULL'};`)
      if (defChanged) {
        if (old.defaultValue) warnings.push(`Drop the existing default constraint on "${c.name}" first (see the table's constraints).`)
        if (c.defaultValue) sql.push(`ALTER TABLE ${ref} ADD DEFAULT ${c.defaultValue} FOR ${col};`)
      }
    } else if (engine === 'oracle') {
      const parts = []
      if (typeChanged) parts.push(c.dataType)
      if (defChanged) parts.push(`DEFAULT ${c.defaultValue || 'NULL'}`)
      if (nullChanged) parts.push(c.nullable ? 'NULL' : 'NOT NULL')
      if (parts.length) sql.push(`ALTER TABLE ${ref} MODIFY (${col} ${parts.join(' ')});`)
    } else if (engine === 'clickhouse') {
      if (typeChanged || nullChanged || defChanged) sql.push(`ALTER TABLE ${ref} MODIFY COLUMN ${columnDef(engine, { ...c, primaryKey: false })};`)
    } else {
      // PostgreSQL family and DuckDB
      if (typeChanged) sql.push(`ALTER TABLE ${ref} ALTER COLUMN ${col} TYPE ${c.dataType}${engine === 'postgres' ? ` USING ${col}::${c.dataType}` : ''};`)
      if (nullChanged) sql.push(`ALTER TABLE ${ref} ALTER COLUMN ${col} ${c.nullable ? 'DROP NOT NULL' : 'SET NOT NULL'};`)
      if (defChanged) sql.push(c.defaultValue ? `ALTER TABLE ${ref} ALTER COLUMN ${col} SET DEFAULT ${c.defaultValue};` : `ALTER TABLE ${ref} ALTER COLUMN ${col} DROP DEFAULT;`)
    }
  }
  return { sql, warnings }
}

export function createIndexSql(engine: Engine, t: TableInfo, name: string, columns: string[], unique: boolean) {
  const q = (n: string) => quote(engine, n)
  if (engine === 'clickhouse') return `ALTER TABLE ${tableRef(engine, t)} ADD INDEX ${q(name)} (${columns.map(q).join(', ')}) TYPE minmax GRANULARITY 1;`
  const ixName = engine === 'postgres' || engine === 'duckdb' || engine === 'oracle' ? q(name) : q(name)
  return `CREATE ${unique ? 'UNIQUE ' : ''}INDEX ${ixName} ON ${tableRef(engine, t)} (${columns.map(q).join(', ')});`
}

export function dropIndexSql(engine: Engine, t: TableInfo, name: string) {
  const q = (n: string) => quote(engine, n)
  if (engine === 'mssql' || engine === 'mysql') return `DROP INDEX ${q(name)} ON ${tableRef(engine, t)};`
  if (engine === 'clickhouse') return `ALTER TABLE ${tableRef(engine, t)} DROP INDEX ${q(name)};`
  if (t.schema && engine !== 'sqlite' && engine !== 'libsql') return `DROP INDEX ${q(t.schema)}.${q(name)};`
  return `DROP INDEX ${q(name)};`
}

/** Ready-to-edit scripts for the sidebar's right-click menu */
export function scriptSelect(engine: Engine, t: TableInfo, columns?: string[], limit = 100) {
  const cols = columns?.length ? columns.map((c) => quote(engine, c)).join(', ') : '*'
  const ref = tableRef(engine, t)
  if (engine === 'mssql') return `SELECT TOP (${limit}) ${cols}\nFROM ${ref};`
  if (engine === 'oracle') return `SELECT ${cols}\nFROM ${ref}\nFETCH FIRST ${limit} ROWS ONLY;`
  return `SELECT ${cols}\nFROM ${ref}\nLIMIT ${limit};`
}

export function scriptInsert(engine: Engine, t: TableInfo, columns: ColumnInfo[]) {
  const cols = columns.filter((c) => !c.autoIncrement)
  return `INSERT INTO ${tableRef(engine, t)} (${cols.map((c) => quote(engine, c.name)).join(', ')})\nVALUES (${cols.map((c) => `/* ${c.name} ${c.dataType} */ NULL`).join(',\n        ')});`
}

export function scriptUpdate(engine: Engine, t: TableInfo, columns: ColumnInfo[]) {
  const pk = columns.filter((c) => c.primaryKey)
  const rest = columns.filter((c) => !c.primaryKey)
  const q = (n: string) => quote(engine, n)
  return `UPDATE ${tableRef(engine, t)}\nSET ${rest.map((c) => `${q(c.name)} = NULL`).join(',\n    ')}\nWHERE ${(pk.length ? pk : columns.slice(0, 1)).map((c) => `${q(c.name)} = NULL`).join(' AND ')};`
}

export function scriptDelete(engine: Engine, t: TableInfo, columns: ColumnInfo[]) {
  const pk = columns.filter((c) => c.primaryKey)
  return `DELETE FROM ${tableRef(engine, t)}\nWHERE ${(pk.length ? pk : columns.slice(0, 1)).map((c) => `${quote(engine, c.name)} = NULL`).join(' AND ')};`
}

export function scriptDrop(engine: Engine, kind: string, t: { schema?: string; name: string }, table?: string) {
  const what = ({ table: 'TABLE', view: 'VIEW', procedure: 'PROCEDURE', function: 'FUNCTION', trigger: 'TRIGGER', sequence: 'SEQUENCE', event: 'EVENT', package: 'PACKAGE', matview: 'MATERIALIZED VIEW', type: 'TYPE', synonym: 'SYNONYM', index: 'INDEX' } as Record<string, string>)[kind] ?? kind.toUpperCase()
  // PostgreSQL function names already include their argument list
  const name = engine === 'postgres' && (kind === 'function' || kind === 'procedure') ? `${t.schema ? quote(engine, t.schema) + '.' : ''}${t.name}` : tableRef(engine, t)
  if (engine === 'postgres' && kind === 'trigger' && table) return `DROP TRIGGER ${quote(engine, t.name)} ON ${tableRef(engine, { schema: t.schema, name: table })};`
  if (engine === 'oracle' || engine === 'mssql') return `DROP ${what} ${name};`
  return `DROP ${what} IF EXISTS ${name};`
}

export function scriptTruncate(engine: Engine, t: TableInfo) {
  if (engine === 'sqlite' || engine === 'libsql') return `DELETE FROM ${tableRef(engine, t)};`
  return `TRUNCATE TABLE ${tableRef(engine, t)};`
}

/** Template to call a procedure or function */
export function scriptExecute(engine: Engine, kind: string, o: { schema?: string; name: string }) {
  const ref = engine === 'postgres' ? `${o.schema ? quote(engine, o.schema) + '.' : ''}${o.name.replace(/\(.*$/, '')}` : tableRef(engine, o)
  if (engine === 'mssql') return kind === 'procedure' ? `EXEC ${ref} /* @param = value */;` : `SELECT ${ref}(/* args */);`
  if (engine === 'oracle') return kind === 'procedure' ? `BEGIN\n  ${ref}(/* args */);\nEND;` : `SELECT ${ref}(/* args */) FROM dual;`
  if (kind === 'procedure') return `CALL ${ref}(/* args */);`
  return `SELECT ${ref}(/* args */);`
}
