import * as L from 'lucide-react'

type P = SVGProps<SVGSVGElement>
const wrap = (I: L.LucideIcon) => {
  const C = (p: P) => <I size={16} strokeWidth={2} {...(p as L.LucideProps)} />
  return C
}

